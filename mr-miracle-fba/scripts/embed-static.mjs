// Embeds public/* into src/static.gen.ts so the Worker serves the dashboard itself (no asset upload needed).
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
const TYPES = { html: "text/html; charset=utf-8", js: "text/javascript; charset=utf-8", css: "text/css; charset=utf-8", svg: "image/svg+xml", ico: "image/x-icon" };
const files = {};
for (const f of readdirSync("public")) {
  const ext = f.split(".").pop();
  files["/" + f] = { type: TYPES[ext] || "application/octet-stream", body: readFileSync("public/" + f, "utf8") };
}
const out = "// Generated by scripts/embed-static.mjs — do not edit.\nexport const STATIC: Record<string, { type: string; body: string }> = " + JSON.stringify(files) + ";\n";
// only write when something changed (otherwise `wrangler dev` sees a change and rebuilds forever)
if (!existsSync("src/static.gen.ts") || readFileSync("src/static.gen.ts", "utf8") !== out) writeFileSync("src/static.gen.ts", out);
console.log("embedded", Object.keys(files).join(", "));
