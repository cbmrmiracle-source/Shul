// Packs the bridge's files into the Worker so it can serve a one-line installer.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const here = path.dirname(fileURLToPath(import.meta.url));
const bridge = path.resolve(here, "../../bridge");
const names = ["package.json", "package-lock.json", "open-chrome.cmd", "open-chrome.sh", "start-bridge.cmd", "start-bridge.sh",
  "src/agent.mjs", "src/browser.mjs", "src/human.mjs", "src/recorder.mjs", "src/snapshot.mjs"];
const read = (n) => fs.readFileSync(path.join(bridge, n), "utf8");
// cmd.exe needs CRLF line endings for labels/goto to work reliably.
const files = Object.fromEntries(names.map((n) => [n, n.endsWith(".cmd") ? read(n).replace(/\r?\n/g, "\r\n") : read(n)]));
fs.writeFileSync(path.resolve(here, "../src/bridge-files.ts"), `// Generated by scripts/bundle-bridge.mjs — do not edit.\nexport const BRIDGE_FILES: Record<string, string> = ${JSON.stringify(files)};\n`);
console.log(`bundled ${names.length} bridge files`);
